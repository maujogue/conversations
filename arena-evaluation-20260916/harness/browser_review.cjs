const { chromium } = require('/tmp/arena-review-UuyMR9NE/repo/src/frontend/node_modules/playwright');
const fs = require('node:fs');
const ROOT = '/tmp/arena-review-UuyMR9NE';
(async () => {
  const auth = JSON.parse(fs.readFileSync(`${ROOT}/artifacts/live-auth.json`));
  const browser = await chromium.launch({headless: true});
  const context = await browser.newContext({viewport: {width: 1440, height: 1000}, locale: 'fr-FR'});
  await context.addCookies([{name: auth.cookie_name, value: auth.cookie_value, domain: '127.0.0.1', path: '/', httpOnly: true, sameSite: 'Lax'}]);
  await context.addCookies([{name: 'csrftoken', value: 'abcdefghijklmnopqrstuvwx12345678', domain: '127.0.0.1', path: '/', sameSite: 'Lax'}]);
  const page = await context.newPage();
  const errors = [];
  const failedResponses = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('response', r => {if (r.status() >= 400) failedResponses.push({url:r.url(),status:r.status()})});
  await page.goto('http://127.0.0.1:23000/', {waitUntil: 'networkidle'});
  await page.screenshot({path: `${ROOT}/artifacts/home-desktop.png`, fullPage: true});
  const findings = {};
  const save = () => fs.writeFileSync(`${ROOT}/artifacts/browser-findings.json`,JSON.stringify(findings,null,2));
  await page.locator('textarea').fill('Reformule ce mail pour un directeur : nous avons reçu votre demande et répondrons vendredi. [LONG]');
  await page.locator('textarea').press('Enter');
  await page.locator('[data-testid="arena-turn"]').waitFor({timeout:30000});
  await page.waitForFunction(() => {const b=document.querySelectorAll('.arena-vote-button');return b.length===2 && [...b].every(x=>!x.disabled)}, null, {timeout:30000});
  const chatUrl = page.url();
  findings.chatUrl = chatUrl;
  findings.voteButtons = await page.locator('.arena-vote-button').allTextContents();
  await page.screenshot({path:`${ROOT}/artifacts/arena-desktop.png`,fullPage:true});
  await page.reload({waitUntil:'networkidle'});
  findings.restored = await page.locator('[data-testid="arena-turn"]').isVisible();
  await page.locator('textarea').fill('Merci, raccourcis la réponse.');
  await page.locator('textarea').press('Enter');
  await page.getByRole('dialog').waitFor({timeout:5000});
  findings.blockingDialog = await page.getByRole('dialog').innerText(); save();
  await page.screenshot({path:`${ROOT}/artifacts/arena-required-vote.png`,fullPage:true});
  await page.reload({waitUntil:'networkidle'});
  await page.locator('.arena-vote-button').nth(1).click();
  await page.locator('[data-testid="arena-turn"]').waitFor({state:'detached'});
  findings.votedCollapsed = true;
  await page.locator('textarea').fill('Merci, raccourcis la réponse.');
  await page.locator('textarea').press('Enter');
  await page.locator('[data-testid="arena-turn"]').waitFor();
  await page.waitForFunction(() => [...document.querySelectorAll('.arena-vote-button')].length===2 && [...document.querySelectorAll('.arena-vote-button')].every(x=>!x.disabled));
  findings.followupWorked = true; save();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:`${ROOT}/artifacts/arena-mobile.png`,fullPage:true});
  findings.mobile = await page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth,buttons:[...document.querySelectorAll('.arena-vote-button')].map(x=>({text:x.innerText,rect:x.getBoundingClientRect().toJSON()})),sides:[...document.querySelectorAll('[data-testid^="arena-side-"]')].map(x=>({rect:x.getBoundingClientRect().toJSON()}))}));
  await page.locator('.arena-vote-button').first().click();
  await page.locator('[data-testid="arena-turn"]').waitFor({state:'detached'});
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('http://127.0.0.1:23000/',{waitUntil:'networkidle'});
  await page.locator('textarea').fill('Réponds brièvement. [FAIL_CHALLENGER]');
  await page.locator('textarea').press('Enter');
  await page.locator('[data-testid="arena-turn"]').waitFor();
  await page.locator('[data-testid="arena-turn"]').waitFor({state:'detached',timeout:45000});
  findings.failedChallengerCollapsed = true;
  await page.screenshot({path:`${ROOT}/artifacts/arena-failure-fallback.png`,fullPage:true});
  await page.goto(`http://127.0.0.1:28071/admin/chat/arenaexperiment/${auth.experiment_id}/results/`,{waitUntil:'networkidle'});
  findings.adminText = await page.locator('body').innerText();
  await page.screenshot({path:`${ROOT}/artifacts/admin-results.png`,fullPage:true});
  findings.errors = errors; findings.failedResponses = failedResponses;
  fs.writeFileSync(`${ROOT}/artifacts/browser-findings.json`,JSON.stringify(findings,null,2));
  console.log(JSON.stringify(findings,null,2));
  await browser.close();
})().catch(e => {console.error(e); process.exit(1)});
